from datetime import datetime, timezone

from sqlalchemy import select

from .models import AlertEvent, AlertRule, Strategy, TradingSignal, UserSettings


def rule_matches_signal(rule, signal):
    condition = rule.condition.upper()
    signal_type = signal.signal_type.upper()
    mentioned_types = {
        signal_name
        for signal_name in ("BUY", "SELL", "HOLD")
        if signal_name in condition
    }
    return not mentioned_types or signal_type in mentioned_types


def create_signal_alert_events(db, signal):
    """Create missing user alert events for one newly-created trading signal."""
    user_settings = {
        settings.user_id: settings
        for settings in db.scalars(select(UserSettings)).all()
    }
    rules = db.scalars(
        select(AlertRule).where(
            AlertRule.ticker == signal.ticker,
            AlertRule.enabled.is_(True),
            AlertRule.destination == "app",
        )
    ).all()
    created = []
    for rule in rules:
        settings = user_settings.get(rule.user_id)
        if settings is not None and not settings.signal_alerts:
            continue
        if not rule_matches_signal(rule, signal):
            continue
        existing = db.scalar(
            select(AlertEvent).where(
                AlertEvent.rule_id == rule.id,
                AlertEvent.signal_id == signal.id,
            )
        )
        if existing is not None:
            continue
        event = AlertEvent(
            user_id=rule.user_id,
            rule_id=rule.id,
            signal_id=signal.id,
            title=f"{signal.ticker} changed to {signal.signal_type}",
            detail=f"{signal.model_name or 'Signal model'} signal generated",
            tone=signal.signal_type.lower(),
            created_at=(
                signal.created_at
                if isinstance(signal.created_at, datetime)
                else datetime.now(timezone.utc).replace(tzinfo=None)
            ),
        )
        db.add(event)
        created.append(event)
    if created:
        db.flush()
    return created


def sync_signal_alert_events(db):
    """Backfill events for existing signals and enabled rules without duplicates."""
    signals = db.scalars(select(TradingSignal)).all()
    created = []
    for signal in signals:
        created.extend(create_signal_alert_events(db, signal))
    if created:
        db.commit()
    return created


def create_live_prediction_signals(db, predictions):
    """Convert live ML prediction rows into trading signals and app alerts."""
    created_signals = []
    for prediction in predictions:
        model_name = str(prediction.get("model_name") or "live_ml")
        ticker = str(prediction.get("ticker") or "").upper()
        prediction_date = str(prediction.get("prediction_date") or "")
        if not ticker or not prediction_date:
            continue

        strategy_name = f"Live {model_name}"
        strategy = db.scalar(select(Strategy).where(Strategy.name == strategy_name))
        if strategy is None:
            strategy = Strategy(
                name=strategy_name,
                description="Live prediction generated by the ML daily job",
                model_name=model_name,
                is_active=True,
            )
            db.add(strategy)
            db.flush()

        existing = db.scalar(
            select(TradingSignal).where(
                TradingSignal.ticker == ticker,
                TradingSignal.strategy_id == strategy.id,
                TradingSignal.signal_date == prediction_date,
            )
        )
        if existing is not None:
            continue

        direction = str(prediction.get("direction") or "flat").lower()
        signal_type = "BUY" if direction == "up" else "SELL" if direction == "down" else "HOLD"
        confidence = float(prediction.get("confidence_score") or 0)
        target_price = prediction.get("predicted_close")
        signal = TradingSignal(
            ticker=ticker,
            strategy_id=strategy.id,
            signal_date=prediction_date,
            signal_type=signal_type,
            confidence_score=max(0.0, min(1.0, confidence)),
            target_price=float(target_price) if target_price is not None else None,
            model_name=model_name,
            created_at=datetime.now(timezone.utc).replace(tzinfo=None),
        )
        db.add(signal)
        db.flush()
        created_signals.append(signal)
        create_signal_alert_events(db, signal)

    if created_signals:
        db.commit()
    else:
        db.rollback()
    return created_signals
